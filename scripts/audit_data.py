#!/usr/bin/env python
"""Factual audit of the DepMap files. Writes docs/data_audit.md and results/data_audit/*.csv.

Usage: python scripts/audit_data.py [--data-dir data] [--cache-dir cache] [--out-md docs/data_audit.md]
       [--out-dir results/data_audit] [--effect-thr -0.5] [--sel-lo 0.05] [--sel-hi 0.95]
Builds the parquet cache (src/essml/io.py) if missing.
"""
import argparse
import re
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from essml import io  # noqa: E402

LEAK_KW = re.compile(r"screen|crispr|achilles|avana|library|dependen|gene.?effect|essential|score|"
                     r"sgrna|guide|drug|treat|resist|anchor|prescreen|datasource|passage|comment", re.I)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--data-dir", default=str(ROOT / "data"))
    ap.add_argument("--cache-dir", default=str(ROOT / "cache"))
    ap.add_argument("--out-md", default=str(ROOT / "docs" / "data_audit.md"))
    ap.add_argument("--out-dir", default=str(ROOT / "results" / "data_audit"))
    ap.add_argument("--effect-thr", type=float, default=-0.5)
    ap.add_argument("--sel-lo", type=float, default=0.05)
    ap.add_argument("--sel-hi", type=float, default=0.95)
    ap.add_argument("--min-lineage", type=int, default=5)
    a = ap.parse_args()
    D, C, O = Path(a.data_dir), Path(a.cache_dir), Path(a.out_dir)
    O.mkdir(parents=True, exist_ok=True)
    Path(a.out_md).parent.mkdir(parents=True, exist_ok=True)
    io.build_cache(D, C)

    md = ["# Data audit", "", f"Generated by `scripts/audit_data.py` from `{D}`. Factual only.", ""]

    def H(t):
        md.extend(["", f"## {t}", ""])

    def P(t=""):
        md.append(t)

    def T(df, name, index=True, show=True):
        df.to_csv(O / f"{name}.csv", index=index)
        if show:
            P(df.to_markdown(index=index) if len(df) <= 60 else df.head(60).to_markdown(index=index)
              + f"\n\n(first 60 of {len(df)} rows; full table in results/data_audit/{name}.csv)")
            P()

    # ---------------- 1. shapes / duplicates
    H("1. Shapes, ModelIDs, default entries")
    shapes, dup_rows = [], []
    meta_by_mod = {}
    for name in ["expression", "cn", "damaging", "hotspot", "fusion"]:
        f = D / io.FILES[name]
        hdr = io.read_header(f)
        mc = [c for c in hdr if c in io.META_COLS]
        m = pd.read_csv(f, usecols=mc)
        meta_by_mod[name] = m
        yes = io.is_default(m["IsDefaultEntryForModel"])
        per = m.groupby("ModelID")["IsDefaultEntryForModel"].apply(lambda s: int(io.is_default(s).sum()))
        rpm = m.groupby("ModelID").size()
        shapes.append(dict(file=io.FILES[name], rows=len(m), cols=len(hdr), unique_models=m["ModelID"].nunique(),
                           rows_per_model_min=rpm.min(), rows_per_model_median=rpm.median(), rows_per_model_max=rpm.max(),
                           models_with_gt1_rows=int((rpm > 1).sum()),
                           default_rows=int(yes.sum()),
                           models_exactly_one_default=int((per == 1).sum()),
                           models_zero_default=int((per == 0).sum()), models_gt1_default=int((per > 1).sum()),
                           IsDefaultEntryForModel_values=";".join(map(str, m["IsDefaultEntryForModel"].unique()))))
    crispr = io.load_matrix("crispr", C)
    shapes.insert(0, dict(file=io.FILES["crispr"], rows=crispr.shape[0], cols=crispr.shape[1] + 1,
                          unique_models=crispr.index.nunique(), rows_per_model_max=1))
    mdl = pd.read_csv(D / "Model.csv")
    mc = pd.read_csv(D / "ModelCondition.csv")
    shapes.append(dict(file="Model.csv", rows=len(mdl), cols=mdl.shape[1], unique_models=mdl["ModelID"].nunique()))
    shapes.append(dict(file="ModelCondition.csv", rows=len(mc), cols=mc.shape[1], unique_models=mc["ModelID"].nunique()))
    sh = pd.DataFrame(shapes)
    T(sh, "shapes", index=False)
    P("Cols for omics files include 5-6 metadata/index columns; CRISPR cols include the index column. "
      "For OmicsFusionFiltered the table is long (one row per fusion); IsDefaultEntryForModel marks all fusion rows of the "
      "default sequencing entry, so 'exactly one default row per model' is not meaningful there.")

    # ---------------- 2. overlap
    H("2. Overlap of screened models with omics")
    scr = set(crispr.index)
    sets = {n: set(meta_by_mod[n].loc[io.is_default(meta_by_mod[n]["IsDefaultEntryForModel"]), "ModelID"])
            for n in ["expression", "cn", "damaging", "hotspot", "fusion"]}
    sets["Model.csv"] = set(mdl["ModelID"])
    rows = [dict(set="CRISPR screened", n=len(scr))]
    for n, s in sets.items():
        rows.append(dict(set=f"{n} (default entries)", n=len(s), screened_in_set=len(scr & s)))
    full = scr & sets["expression"] & sets["cn"] & sets["damaging"]
    rows.append(dict(set="screened ∩ expression ∩ cn ∩ damaging (full omics)", n=len(full), screened_in_set=len(full)))
    full2 = full & sets["hotspot"]
    rows.append(dict(set="... ∩ hotspot", n=len(full2), screened_in_set=len(full2)))
    rows.append(dict(set="screened missing from Model.csv", n=len(scr - sets["Model.csv"])))
    rows.append(dict(set="expression ∩ cn ∩ damaging, NOT screened (inference-only lines)",
                     n=len((sets["expression"] & sets["cn"] & sets["damaging"]) - scr)))
    T(pd.DataFrame(rows), "overlap", index=False)
    mm = mdl.set_index("ModelID")
    lin = mm.loc[sorted(full & set(mm.index)), "OncotreeLineage"].fillna("NA").value_counts()
    lin_all = mm.loc[sorted(scr & set(mm.index)), "OncotreeLineage"].fillna("NA").value_counts()
    lt = pd.DataFrame({"screened_full_omics": lin, "screened_any_omics": lin_all}).fillna(0).astype(int)
    lt = lt.sort_values("screened_full_omics", ascending=False)
    lt.index.name = "OncotreeLineage"
    P("Counts per OncotreeLineage (screened, full omics = expression+cn+damaging):")
    T(lt, "lineage_counts")
    small = lt[lt["screened_full_omics"] < a.min_lineage]
    P(f"Lineages with < {a.min_lineage} screened full-omics lines: " +
      (", ".join(f"{i} ({r.screened_full_omics})" for i, r in small.iterrows()) or "none"))

    # ---------------- 3. patient sharing
    H("3. PatientID sharing among screened models")
    sm = mm.loc[sorted(scr & set(mm.index))]
    grp = sm.groupby("PatientID")["PatientID"].transform("size")
    shared = sm[grp > 1].copy()
    allp = mm.groupby("PatientID")["PatientID"].transform("size")
    P(f"Screened models with PatientID: {sm['PatientID'].notna().sum()} / {len(sm)}")
    P(f"Screened models sharing a PatientID with another *screened* model: {len(shared)} in "
      f"{shared['PatientID'].nunique()} groups")
    sh_any = sm[(allp.reindex(sm.index) > 1)]
    P(f"Screened models sharing a PatientID with any other model in Model.csv: {len(sh_any)} in "
      f"{sh_any['PatientID'].nunique()} groups")
    gl = shared.reset_index().groupby("PatientID").agg(
        n=("ModelID", "size"), models=("ModelID", ", ".join), names=("CellLineName", " | ".join),
        lineage=("OncotreeLineage", lambda s: ";".join(sorted(set(map(str, s)))))).sort_values("n", ascending=False)
    P("Groups (screened only):")
    T(gl, "patient_groups_screened")
    gl_full = shared.loc[shared.index.isin(full)]
    P(f"Of these, with full omics: {len(gl_full)} models in {gl_full['PatientID'].nunique()} groups"
      " (note a group may shrink to 1 after restricting to full-omics lines).")

    # ---------------- 4. gene columns
    H("4. Gene columns")
    gi = {}
    grows = []
    for name in io.MATRICES:
        hdr = io.read_header(D / io.FILES[name])
        _, parsed, bad = io.split_columns(hdr)
        sy = pd.Series([p[1] for p in parsed]); en = pd.Series([p[2] for p in parsed])
        gi[name] = set(en)
        grows.append(dict(matrix=name, gene_columns=len(parsed), unparseable=len(bad),
                          unparseable_examples=";".join(map(str, bad[:5])),
                          duplicated_symbols=int(sy.duplicated().sum()), duplicated_entrez=int(en.duplicated().sum()),
                          dup_symbol_examples=";".join(sy[sy.duplicated()].unique()[:5])))
    T(pd.DataFrame(grows), "gene_columns", index=False)
    cg = gi["crispr"]
    orows = [dict(matrix=n, n_genes=len(s), overlap_with_crispr=len(s & cg), crispr_genes_not_in=len(cg - s),
                  not_in_crispr=len(s - cg)) for n, s in gi.items()]
    T(pd.DataFrame(orows), "gene_overlap", index=False)
    allm = cg & gi["expression"] & gi["cn"] & gi["damaging"]
    P(f"CRISPR ∩ expression ∩ cn ∩ damaging genes (by Entrez): {len(allm)}")
    P(f"Damaging-mutation genes also in expression: {len(gi['damaging'] & gi['expression'])}; "
      f"hotspot genes in CRISPR: {len(gi['hotspot'] & cg)} / {len(gi['hotspot'])}")

    # ---------------- 5. CRISPR
    H("5. CRISPR gene-effect matrix")
    X = crispr.to_numpy(dtype=np.float32)
    nanm = np.isnan(X)
    P(f"Shape {X.shape}; total NaN fraction {nanm.mean():.5f}")
    ng = nanm.sum(0); nl = nanm.sum(1)
    P(f"Genes with any NaN: {(ng > 0).sum()} ({(ng>0).mean():.3%}); genes with >=10% NaN: {(ng/X.shape[0] >= .1).sum()}; "
      f"genes all-NaN: {(ng == X.shape[0]).sum()}")
    P(f"Lines with any NaN: {(nl > 0).sum()}; lines with >=10% NaN genes: {(nl/X.shape[1] >= .1).sum()}; "
      f"max line NaN fraction {nl.max()/X.shape[1]:.4f}")
    gmean = np.nanmean(X, 0); gsd = np.nanstd(X, 0, ddof=1)
    lowfrac = np.nanmean(np.where(nanm, np.nan, X < a.effect_thr), 0)
    sel = (lowfrac >= a.sel_lo) & (lowfrac <= a.sel_hi)
    lmed = np.nanmedian(X, 1)
    qs = [0, .001, .01, .05, .25, .5, .75, .95, .99, .999, 1]
    qv = np.nanquantile(X[~nanm][::7], qs)  # subsample every 7th non-NaN value
    P(f"Effect thr = {a.effect_thr}: genes with mean < thr: {(gmean < a.effect_thr).sum()}; genes with SD > 0.25: {(gsd > .25).sum()}; "
      f"'selective' genes (fraction of lines < thr in [{a.sel_lo}, {a.sel_hi}]): {sel.sum()}; "
      f"genes with fraction-below > {a.sel_hi} (common essential-like): {(lowfrac > a.sel_hi).sum()}; "
      f"genes never below thr: {(lowfrac == 0).sum()}")
    P("Quantiles of all gene-effect values (every 7th non-NaN value): " +
      ", ".join(f"q{q}={v:.3f}" for q, v in zip(qs, qv)))
    P("Per-line median of effects, quantiles: " + ", ".join(f"q{q}={v:.3f}" for q, v in zip(qs, np.nanquantile(lmed, qs))))
    P("Per-gene mean, quantiles: " + ", ".join(f"q{q}={v:.3f}" for q, v in zip(qs, np.nanquantile(gmean, qs))))
    P("Per-gene SD, quantiles: " + ", ".join(f"q{q}={v:.3f}" for q, v in zip(qs, np.nanquantile(gsd, qs))))
    gs = pd.DataFrame({"entrez": crispr.columns, "mean": gmean, "sd": gsd, "frac_below_thr": lowfrac, "n_nan": ng})
    gs.to_csv(O / "crispr_gene_stats.csv", index=False)
    ls = pd.DataFrame({"ModelID": crispr.index, "median": lmed, "n_nan": nl,
                       "frac_below_thr": np.nanmean(np.where(nanm, np.nan, X < a.effect_thr), 1)})
    ls.to_csv(O / "crispr_line_stats.csv", index=False)
    P("Per-gene and per-line tables: `crispr_gene_stats.csv`, `crispr_line_stats.csv`.")
    del X, nanm

    # ---------------- 6. omics value domains
    H("6. Omics value scales")
    vrows = []
    for name in ["expression", "cn", "damaging", "hotspot"]:
        M = io.load_matrix(name, C)
        v = M.to_numpy(dtype=np.float32)
        nn = np.isnan(v)
        r = dict(matrix=name, models=v.shape[0], genes=v.shape[1], nan_frac=float(nn.mean()),
                 genes_with_nan=int(nn.any(0).sum()), models_with_nan=int(nn.any(1).sum()),
                 min=float(np.nanmin(v)), max=float(np.nanmax(v)), mean=float(np.nanmean(v)))
        sub = v[::max(1, v.shape[0] // 400)]
        sub = sub[~np.isnan(sub)]
        r.update({f"q{q}": float(np.quantile(sub, q)) for q in (.001, .01, .5, .99, .999)})
        sd = np.nanstd(v, 0)
        r["zero_variance_genes"] = int((sd == 0).sum())
        if name in ("damaging", "hotspot"):
            u, c = np.unique(v[~nn], return_counts=True)
            r["unique_values"] = ";".join(f"{x:g}:{n}" for x, n in zip(u[:12], c[:12])) + (" ..." if len(u) > 12 else "")
            per = np.nansum(v > 0, 1)
            r["mutated_genes_per_line_median"] = float(np.median(per))
            r["mutated_genes_per_line_min_max"] = f"{per.min()}-{per.max()}"
            r["genes_never_mutated"] = int((np.nansum(v > 0, 0) == 0).sum())
            r["models_with_zero_mutated_genes"] = int((per == 0).sum())
            pd.DataFrame({"ModelID": M.index, "n_mutated_genes": per}).to_csv(O / f"{name}_per_line.csv", index=False)
        if name == "cn":
            r["frac_values_eq_1_exact"] = float((sub == 1).mean())
            r["frac_values_lt_0"] = float((sub < 0).mean())
            r["median_per_line_median"] = float(np.median(np.nanmedian(v, 1)))
        if name == "expression":
            r["frac_exact_zero"] = float((sub == 0).mean())
        vrows.append(r)
        del v, M
    T(pd.DataFrame(vrows).set_index("matrix").T, "omics_value_domains")
    fu = io.load_matrix("fusion", C)
    fpm = fu.groupby("ModelID").size()
    P(f"Fusions (default entries): {len(fu)} rows, {fu['ModelID'].nunique()} models; fusions per model: "
      f"median {fpm.median():.0f}, mean {fpm.mean():.2f}, max {fpm.max()}; models in Model.csv w/o fusion row: "
      f"{len(sets['expression'] - set(fpm.index))} of expression models")
    ff = fu.groupby("CanonicalFusionName")["ModelID"].nunique().sort_values(ascending=False).head(25)
    ff.name = "n_models"
    T(ff.to_frame(), "fusion_top")
    pd.DataFrame({"n_fusions": fpm}).to_csv(O / "fusion_per_line.csv")

    # ---------------- 7. Model.csv
    H("7. Model.csv / ModelCondition.csv")
    sm = mm.loc[sorted(scr & set(mm.index))]
    P("ModelType among screened:")
    T(sm["ModelType"].fillna("NA").value_counts().to_frame("n"), "modeltype_screened")
    P("ModelType among all models:")
    T(mm["ModelType"].fillna("NA").value_counts().to_frame("n"), "modeltype_all")
    nc_mask = mm.apply(lambda r: r.astype(str).str.contains("non-cancerous", case=False).any(), axis=1)
    nc = sm[sm.index.isin(mm.index[nc_mask])]
    P(f"Models matching 'Non-Cancerous' in any Model.csv column: {int(nc_mask.sum())} total, {len(nc)} screened.")
    if len(nc):
        ncd = nc[["CellLineName", "OncotreeLineage", "OncotreePrimaryDisease", "OncotreeSubtype", "ModelType", "SourceType"]].copy()
        ncd["has_expression"] = ncd.index.isin(sets["expression"])
        ncd["has_cn"] = ncd.index.isin(sets["cn"])
        ncd["has_damaging"] = ncd.index.isin(sets["damaging"])
        ncd["full_omics"] = ncd.index.isin(full)
        T(ncd, "noncancerous_screened")
    # column review
    rows = []
    for fname, df in (("Model.csv", mdl), ("ModelCondition.csv", mc)):
        for c in df.columns:
            nu = df[c].nunique(dropna=True)
            ex = ";".join(map(str, df[c].dropna().unique()[:4]))[:80]
            rows.append(dict(file=fname, column=c, non_null=int(df[c].notna().sum()), n_unique=nu, examples=ex,
                             keyword_flag=bool(LEAK_KW.search(c))))
    cr = pd.DataFrame(rows)
    # compare between screened and unscreened non-null rate for each Model.csv column (availability asymmetry)
    asym = {}
    for c in mdl.columns:
        s = mdl[c].notna()
        asym[c] = (s[mdl["ModelID"].isin(scr)].mean(), s[~mdl["ModelID"].isin(scr)].mean())
    cr["nonnull_rate_screened"] = [asym[c][0] if f == "Model.csv" else np.nan for f, c in zip(cr.file, cr.column)]
    cr["nonnull_rate_unscreened"] = [asym[c][1] if f == "Model.csv" else np.nan for f, c in zip(cr.file, cr.column)]
    T(cr, "model_columns_review", show=False)
    P("Column inventory with keyword flags (screen/crispr/drug/treatment/passage/comment/...): `model_columns_review.csv`.")
    P("Keyword-flagged columns:")
    T(cr[cr.keyword_flag][["file", "column", "non_null", "n_unique", "examples"]], "model_columns_flagged", index=False)
    P("Model.csv columns whose non-null rate differs by >0.2 between screened and unscreened models:")
    d = cr[(cr.file == "Model.csv") & ((cr.nonnull_rate_screened - cr.nonnull_rate_unscreened).abs() > .2)]
    T(d[["column", "non_null", "nonnull_rate_screened", "nonnull_rate_unscreened"]], "model_columns_asymmetric", index=False)
    P("ModelCondition: rows per ModelID and DataSource / CellFormat breakdown (screened models):")
    mcs = mc[mc["ModelID"].isin(scr)]
    P("Screened vs unscreened by Model.csv `EngineeredModel`:")
    T(pd.crosstab(mm["EngineeredModel"].fillna("NA"), mm.index.isin(scr)).rename(columns={False: "unscreened", True: "screened"}), "engineered_by_screened")
    for c in ("DataSource", "CellFormat", "PrescreenTreatmentDrug", "AnchorDrug"):
        if c in mcs:
            P(f"- `{c}` among ModelCondition rows of screened models: " +
              "; ".join(f"{k}={v}" for k, v in mcs[c].fillna("NA").value_counts().head(8).items()))
    # release version hints
    P("")
    P("Release-version hints (regex `2[0-9]Q[1-4]|release|public` over file names, headers, text columns):")
    hints = []
    for f in sorted(D.glob("*")):
        if f.is_file() and re.search(r"2\dQ\d|release", f.name, re.I):
            hints.append(f"file name: {f.name}")
    for df, fn in ((mdl, "Model.csv"), (mc, "ModelCondition.csv")):
        for c in df.select_dtypes(object).columns:
            hit = df[c].dropna().astype(str)
            hit = hit[hit.str.contains(r"2\dQ\d", regex=True)]
            if len(hit):
                hints.append(f"{fn}:{c}: {len(hit)} values e.g. {hit.iloc[0][:80]}")
    cfg = ROOT / "configs"
    P("\n".join(f"- {h}" for h in hints) if hints else "- none found in the data files themselves (version must come from the download source/DATA.md)")
    if cfg.exists():
        P(f"- files in configs/: {', '.join(p.name for p in cfg.glob('*'))}")
    P("- note: hits above are free-text mentions of older releases, not the version of this download; no column or file name encodes the release.")

    Path(a.out_md).write_text("\n".join(md) + "\n", encoding="utf-8")
    print("wrote", a.out_md)


if __name__ == "__main__":
    main()
